#[test]
fn unknown_and_machine_local_fields_are_rejected_and_not_emitted() {
    let unknown = "version = 1\nr-version = \"4.4\"\nenvironment = \"default\"\npackages = []\nartifact-url = \"/tmp/a\"\n";
    assert!(matches!(from_toml(unknown), Err(LockWireError::Parse(_))));
    let platform = "version = 1\nr-version = \"4.4\"\nenvironment = \"default\"\nos = \"linux\"\narch = \"x86_64\"\npackages = []\n";
    assert!(matches!(from_toml(platform), Err(LockWireError::Parse(_))));
    let package_machine_local = "version = 1\nr-version = \"4.4\"\nenvironment = \"default\"\n[[packages]]\nname = \"foo\"\nversion = \"1.0\"\nsource = { kind = \"registry\", namespace = \"cran\" }\ndependencies = []\nvisible-repository-ids = []\nartifact-url = \"/tmp/a\"\n";
    assert!(matches!(
        from_toml(package_machine_local),
        Err(LockWireError::Parse(_))
    ));
    let text = to_toml(&logical_lock()).unwrap();
    for forbidden in [
        "artifact-url",
        "cache-path",
        "link-method",
        "artifact-sha256",
        "size",
        "identity",
        "published-version-spelling",
        "distributions",
        "resolutions",
    ] {
        assert!(!text.contains(forbidden), "unexpected field {forbidden}");
    }
    assert!(!text.contains("\nos = "));
    assert!(!text.contains("\narch = "));
}

