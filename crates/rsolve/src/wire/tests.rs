#[test]
fn r_requirement_is_canonicalized_and_required_on_wire() {
    let requirement = VersionConstraint::new(vec![
        VersionClause::new(RelationOp::Ge, version("3.0.0")),
        VersionClause::new(RelationOp::Le, version("4.0")),
        VersionClause::new(RelationOp::Ge, version("3.0")),
    ]);
    let lock = Lockfile::new(
        Sha256Digest::new("a".repeat(64)).unwrap(),
        requirement,
        LockedResolution {
            target: rsolve_core::ResolutionTarget::new(version("4.0")),
            environment: EnvironmentId::new("default").unwrap(),
            publication_cutoff: None,
            packages: Vec::new(),
        },
    )
    .unwrap();
    let text = to_toml(&lock).unwrap();
    assert!(text.contains("r-requirement = \"<=4.0,>=3.0\""));
    assert_eq!(from_toml(&text).unwrap(), lock);

    let noncanonical = text.replace(
        "r-requirement = \"<=4.0,>=3.0\"",
        "r-requirement = \" >= 3.0, <= 4.0 \"",
    );
    assert!(matches!(
        from_toml(&noncanonical),
        Err(LockWireError::InvalidField { field, .. }) if field == "r-requirement"
    ));
    let missing_digest = text.replace(
        "resolution-intent-sha256 = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
        "",
    );
    assert!(matches!(
        from_toml(&missing_digest),
        Err(LockWireError::Parse(_))
    ));
    let invalid_digest = text.replace(
        "resolution-intent-sha256 = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"",
        "resolution-intent-sha256 = \"invalid\"",
    );
    assert!(matches!(
        from_toml(&invalid_digest),
        Err(LockWireError::InvalidField { field, .. }) if field == "resolution-intent-sha256"
    ));
    let mut incompatible = lock.clone();
    incompatible.r_requirement = VersionConstraint::from_clause(RelationOp::Ge, version("5.0"));
    assert!(matches!(
        to_toml(&incompatible),
        Err(LockWireError::Domain(LockError::RRequirementMismatch))
    ));
    let incompatible_wire = text.replace(
        "r-requirement = \"<=4.0,>=3.0\"",
        "r-requirement = \">=5.0\"",
    );
    assert!(matches!(
        from_toml(&incompatible_wire),
        Err(LockWireError::Domain(LockError::RRequirementMismatch))
    ));
}

#[test]
fn resolution_projection_excludes_artifacts_and_unselected_dependencies() {
    let name = package("artifactless");
    let release_version = version("1.0");
    let release = rsolve_core::PackageRelease::try_from(ReleaseObservation {
        identity: identity(
            "artifactless",
            Provenance::RegistryRelease {
                namespace: PackageNamespace::new("cran").unwrap(),
                version: release_version.clone(),
            },
        ),
        observed_package: name,
        observed_version: release_version,
        metadata: ReleaseMetadata::default(),
        publication: None,
        declared_dependencies: vec![
            DeclaredDependency::from_parts(
                DependencyKind::Depends,
                package("R"),
                DependencySourceConstraint::Any,
                VersionConstraint::unconstrained(),
            )
            .unwrap(),
            DeclaredDependency::from_parts(
                DependencyKind::Imports,
                package("kept"),
                DependencySourceConstraint::Any,
                VersionConstraint::unconstrained(),
            )
            .unwrap(),
            DeclaredDependency::from_parts(
                DependencyKind::Suggests,
                package("suggested"),
                DependencySourceConstraint::Any,
                VersionConstraint::unconstrained(),
            )
            .unwrap(),
        ],
        distributions: vec![Distribution {
            registry: RegistryId::new("cran").unwrap(),
            channel: DistributionChannel::new("source").unwrap(),
            snapshot: None,
            artifacts: vec![rsolve_core::Artifact::Source(SourceArtifact {
                locator: ArtifactLocator::new("/machine/secret.tar.gz").unwrap(),
                upstream_checksums: vec![UpstreamChecksum::Md5("deadbeef".into())],
                size: Some(4242),
            })],
            observed_metadata: DistributionMetadata::default(),
        }],
    })
    .unwrap();
    let resolution = rsolve_core::Resolution::new(
        rsolve_core::ResolutionTarget::new(version("4.4")),
        vec![rsolve_core::ResolvedPackage::new(
            rsolve_core::SolverKey::InstalledName(package("artifactless")),
            release,
            Vec::new(),
            Vec::new(),
        )],
    );
    let lock = Lockfile::from_resolution_with_applicability(
        &resolution,
        EnvironmentId::new("default").unwrap(),
        None,
        Sha256Digest::new("a".repeat(64)).unwrap(),
        VersionConstraint::unconstrained(),
    )
    .unwrap();
    let text = to_toml(&lock).unwrap();
    for forbidden in [
        "/machine/secret.tar.gz",
        "deadbeef",
        "4242",
        "suggested",
        "kept",
    ] {
        assert!(!text.contains(forbidden));
    }
    assert!(!text.contains("\"R\""));
}

#[test]
fn reader_requires_version_one_and_rejects_removed_headers_and_wrappers() {
    assert!(from_toml(empty_wire()).is_ok());
    for input in [
        "schema-version = 1\nversion = 1\nr-version = \"4.4\"\nenvironment = \"default\"\npackages = []\n",
        "schema-revision = 1\nversion = 1\nr-version = \"4.4\"\nenvironment = \"default\"\npackages = []\n",
        "version = 1\nr-version = \"4.4\"\nenvironment = \"default\"\npackages = []\nresolutions = []\n",
    ] {
        assert!(matches!(from_toml(input), Err(LockWireError::Parse(_))));
    }
    for version in [0, 2, 3] {
        let input = format!(
            "version = {version}\nr-version = \"4.4\"\nr-requirement = \"*\"\nresolution-intent-sha256 = \"{}\"\nenvironment = \"default\"\npackages = []\n",
            "1".repeat(64)
        );
        assert!(matches!(
            from_toml(&input),
            Err(LockWireError::UnsupportedSchema { version: found, .. }) if found == version
        ));
    }
}

